const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH});
 const page=await browser.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 let pending=true,attempts=0,disabled=false;
 await page.route('**/api/status',r=>r.fulfill({json:{recovery_pending:pending,offline_recovery_available:pending,active:false,disabled,recovery_confirmation:{ok:false,error:"DNS после восстановления не подтверждён"},probe:{}}}));
 await page.route('**/api/recovery',r=>{
  assert.equal(r.request().postDataJSON().password,'retry-password');
  attempts++;
  if(attempts===1)return r.fulfill({status:409,json:{error:'USB пока недоступна'}});
  pending=false;disabled=!!r.request().postDataJSON().offline;return r.fulfill({json:{ok:true,offline:disabled,backup:'profile-test'}});
 });
 await page.goto('http://127.0.0.1:18088');
 await page.locator('#login-form input[name=password]').fill('preview-password');
 await page.locator('#login-form button').click();
 await page.locator('#recovery-warning:not(.hidden)').waitFor();
 assert.equal(await page.locator('#vpn-desc').textContent(),'DNS после восстановления не подтверждён');
 await page.locator('[data-view=stability]').click();
 await page.locator('#tab-stability-recovery').click();
 const password=page.getByLabel('Пароль для завершения восстановления');
 const retry=page.getByRole('button',{name:'Повторить восстановление',exact:true});
 await password.fill('retry-password');await retry.click();
 await page.getByText('USB пока недоступна',{exact:true}).waitFor();
 assert.equal(await password.inputValue(),'');
 await password.fill('retry-password');await retry.click();
 await page.locator('#recovery-warning.hidden').waitFor({state:'attached'});
 assert.equal(await password.inputValue(),'');assert.equal(attempts,2);
 pending=true;
 await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
 await page.locator('#recovery-warning:not(.hidden)').waitFor();
 const offline=page.getByRole('button',{name:'Восстановить с выключенным VPN',exact:true});
 await password.fill('retry-password');page.once('dialog',d=>d.dismiss());await offline.click();assert.equal(attempts,2);assert.equal(await password.inputValue(),'');
 await password.fill('retry-password');page.once('dialog',d=>d.accept());await offline.click();
 await page.locator('#recovery-warning.hidden').waitFor({state:'attached'});
 assert.equal(attempts,3);assert.equal(disabled,true);assert.equal(await password.inputValue(),'');
 await page.getByRole('button',{name:'Включить VPN',exact:true}).waitFor();
 assert.equal(await offline.count(),0);assert.equal(await page.locator('#connection').textContent(),'○ VPN выключен');
 await page.locator('[data-view=servers]').click();await page.getByRole('button',{name:'+ Добавить сервер',exact:true}).waitFor();
 assert.deepEqual(errors,[]);await browser.close();
 console.log('PASS: recovery banner, failed/successful retry, offline confirmation/cancel, password clearing, VPN remains off and server selection unlocked');
})().catch(e=>{console.error(e);process.exit(1)});
