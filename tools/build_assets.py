#!/usr/bin/env python3
"""Generate gzip-only embedded UI assets; raw HTML/JS/CSS remain editable source."""
import argparse
import gzip
import hashlib
import io
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'web'
GENERATED = WEB / 'assets_generated.go'


def sources():
    return sorted([WEB / 'index.html', *WEB.glob('js/**/*.js'), *WEB.glob('css/**/*.css')])


def source_hashes():
    return {p.relative_to(WEB).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources()}


def generate():
    lines = ['// Code generated by tools/build_assets.py; DO NOT EDIT.', 'package web', '',
             'var compressedAssets = map[string]compressedAsset{']
    for path in sources():
        data = path.read_bytes()
        name = path.relative_to(WEB).as_posix()
        output = io.BytesIO()
        # GzipFile emits a fixed header, independent of the source path/date.
        with gzip.GzipFile(fileobj=output, mode='wb', filename='', mtime=0, compresslevel=9) as target:
            target.write(data)
        compressed = output.getvalue()
        url = '/' if name == 'index.html' else '/' + name
        kind = {'.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css'}[path.suffix]
        digest = hashlib.sha256(data).hexdigest()
        lines.extend([f'\t// source-sha256 {name} {digest}',
                      f'\t"{url}": {{size: {len(data)}, contentType: "{kind}; charset=utf-8", etag: `W/"{digest}"`, data:'])
        chunks = [compressed[i:i + 32] for i in range(0, len(compressed), 32)]
        for index, chunk in enumerate(chunks):
            suffix = ' +' if index < len(chunks) - 1 else '},'
            lines.append('\t\t"' + ''.join(f'\\x{byte:02x}' for byte in chunk) + '"' + suffix)
    lines.extend(['}', ''])
    GENERATED.write_text('\n'.join(lines))


def check():
    if not GENERATED.exists():
        return False
    # Verify source hashes, not zlib byte output across Python/zlib versions.
    recorded = dict(re.findall(r'// source-sha256 (\S+) ([0-9a-f]{64})', GENERATED.read_text()))
    return recorded == source_hashes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if not check():
            raise SystemExit('UI assets are stale; run python3 tools/build_assets.py')
    else:
        generate()
        print('Compressed UI assets generated')


if __name__ == '__main__':
    main()
