#!/usr/bin/env python3
"""Embed the Vite production build; fingerprint every editable frontend input."""
import argparse
import gzip
import hashlib
import io
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'web'
GENERATED = WEB / 'assets_generated.go'
ASSETS = ('index.html', 'assets/panel.js', 'assets/panel.css')


def sources():
    return sorted([*(WEB / 'src').rglob('*'), *[WEB / n for n in
        ('index.html', 'package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts')]])


def source_hashes():
    return {p.relative_to(WEB).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sources() if p.is_file()}


def generate():
    lines = ['// Code generated by tools/build_assets.py; DO NOT EDIT.', 'package web', '']
    for name, digest in source_hashes().items():
        lines.append(f'// source-sha256 {name} {digest}')
    lines.extend(['', 'var compressedAssets = map[string]compressedAsset{'])
    for name in ASSETS:
        path = WEB / 'dist' / name
        if not path.is_file():
            raise SystemExit('Vite build missing; run npm ci --prefix web && npm run --prefix web build')
        data = path.read_bytes()
        output = io.BytesIO()
        with gzip.GzipFile(fileobj=output, mode='wb', filename='', mtime=0, compresslevel=9) as target:
            target.write(data)
        compressed = output.getvalue()
        url = '/' if name == 'index.html' else '/' + name
        kind = {'.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css'}[path.suffix]
        digest = hashlib.sha256(data).hexdigest()
        lines.append(f'\t"{url}": {{size: {len(data)}, contentType: "{kind}; charset=utf-8", etag: `W/"{digest}"`, data:')
        chunks = [compressed[i:i + 32] for i in range(0, len(compressed), 32)]
        for index, chunk in enumerate(chunks):
            suffix = ' +' if index < len(chunks) - 1 else '},'
            lines.append('\t\t"' + ''.join(f'\\x{byte:02x}' for byte in chunk) + '"' + suffix)
    lines.extend(['}', ''])
    GENERATED.write_text('\n'.join(lines))


def check():
    if not GENERATED.exists():
        return False
    recorded = dict(re.findall(r'// source-sha256 (\S+) ([0-9a-f]{64})', GENERATED.read_text()))
    return recorded == source_hashes()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if not check():
            raise SystemExit('UI assets are stale; run npm ci --prefix web && npm run --prefix web build')
    else:
        generate()
        print('Vite production assets embedded')


if __name__ == '__main__':
    main()
